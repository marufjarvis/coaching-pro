export const getTranslation = (lang = 'BN') => {
  const selected = (lang === 'EN') ? 'EN' : 'BN';
  return translations[selected] || translations.BN;
};

export function useTranslation(propLang) {
  const [lang, setLang] = useState(() => propLang || (typeof window !== 'undefined' ? (localStorage.getItem('coachingLanguage') || 'BN') : 'BN'));

  useEffect(() => {
    if (propLang) {
      setLang(propLang);
    }
  }, [propLang]);

  useEffect(() => {
    const onLangChange = (e) => {
      setLang(e.detail || localStorage.getItem('coachingLanguage') || 'BN');
    };
    window.addEventListener('coaching-language-change', onLangChange);
    return () => window.removeEventListener('coaching-language-change', onLangChange);
  }, []);

  const t = getTranslation(lang);
  const switchLang = (newLang) => {
    const selected = (newLang === 'EN') ? 'EN' : 'BN';
    localStorage.setItem('coachingLanguage', selected);
    window.dispatchEvent(new CustomEvent('coaching-language-change', { detail: selected }));
    setLang(selected);
  };

  return { t, lang, setLang: switchLang };
}
